import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const localesDir = fileURLToPath(new URL('../src/locales/', import.meta.url));
const locales = ['en', 'ar'] as const;
const docs = {
  en: 'Typed English message tree. One namespace per file in `src/locales/en/`.',
  ar: 'Arabic message tree. Mirror every namespace file in `src/locales/en/`.',
} as const;

/**
 * Builds the `en.ts` and `ar.ts` aggregators from the namespace files in `src/locales/{locale}/`.
 * `schema.d.ts` derives the message types from `typeof en`, so new files are typed automatically.
 */
export function generateLocaleTypes(): boolean {
  let changed = false;

  for (const locale of locales) {
    const namespaces = readdirSync(`${localesDir}${locale}`)
      .filter((file) => file.endsWith('.json'))
      .map((file) => file.slice(0, -'.json'.length))
      .sort();

    const content = [
      `// Generated by scripts/generate-locale-types.ts from src/locales/${locale}/*.json. Do not edit.`,
      ...namespaces.map((name) => `import ${name} from './${locale}/${name}.json';`),
      '',
      `/** ${docs[locale]} */`,
      `const ${locale} = {`,
      ...namespaces.map((name) => `  ${name},`),
      '};',
      '',
      `export default ${locale};`,
      '',
    ].join('\n');

    const outFile = `${localesDir}${locale}.ts`;
    let current = '';
    try {
      current = readFileSync(outFile, 'utf8');
    } catch {
      // First run: the file does not exist yet.
    }
    if (current !== content) {
      writeFileSync(outFile, content);
      changed = true;
    }
  }

  return changed;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  generateLocaleTypes();
}
